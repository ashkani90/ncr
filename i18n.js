var currentLang = 'fa';

function setDirection(lang) {
    var html = document.documentElement;
    var body = document.body;
    if (lang === 'fa') {
        html.dir = 'rtl';
        html.lang = 'fa';
        html.style.direction = 'rtl';
        body.style.direction = 'rtl';
        body.style.textAlign = 'right';
        html.classList.remove('ltr');
        html.classList.add('rtl');
    } else {
        html.dir = 'ltr';
        html.lang = lang;
        html.style.direction = 'ltr';
        body.style.direction = 'ltr';
        body.style.textAlign = 'left';
        html.classList.remove('rtl');
        html.classList.add('ltr');
    }
}

function setLanguage(lang) {
    if (!TRANSLATIONS[lang]) { return; }
    currentLang = lang;
    localStorage.setItem('userLanguage', lang);
    sessionStorage.setItem('userLanguage', lang);
    setDirection(lang);
    
    // ترجمه عناصر با data-i18n
    var els = document.querySelectorAll('[data-i18n]');
    for (var i = 0; i < els.length; i++) {
        var el = els[i];
        var key = el.getAttribute('data-i18n');
        if (TRANSLATIONS[lang] && TRANSLATIONS[lang][key] !== undefined) {
            el.textContent = TRANSLATIONS[lang][key];
        }
    }
    
    // ترجمه placeholder ها
    var phs = document.querySelectorAll('[data-i18n-placeholder]');
    for (var i = 0; i < phs.length; i++) {
        var el = phs[i];
        var key = el.getAttribute('data-i18n-placeholder');
        if (TRANSLATIONS[lang] && TRANSLATIONS[lang][key] !== undefined) {
            el.placeholder = TRANSLATIONS[lang][key];
        }
    }
    
    // بروزرسانی دکمه‌های زبان
    var btns = document.querySelectorAll('.lang-btn');
    for (var i = 0; i < btns.length; i++) {
        var btn = btns[i];
        if (btn.getAttribute('data-lang') === lang) {
            btn.className = 'lang-btn active';
        } else {
            btn.className = 'lang-btn';
        }
    }
    
    // بروزرسانی سلکتور زبان
    var selector = document.getElementById('languageSelector');
    if (selector) { selector.value = lang; }
}
function translate(key) {
    if (TRANSLATIONS[currentLang] && TRANSLATIONS[currentLang][key] !== undefined) {
        return TRANSLATIONS[currentLang][key];
    }
    return key;
}

document.addEventListener('DOMContentLoaded', function() {
    var savedLang = localStorage.getItem('userLanguage') || 'fa';
    if (TRANSLATIONS[savedLang]) {
        setLanguage(savedLang);
    }
});

window.TRANSLATIONS = TRANSLATIONS;
window.setLanguage = setLanguage;
window.setDirection = setDirection;
window.translate = translate;
window.currentLang = currentLang;